from __future__ import annotations
import argparse
import json
from pathlib import Path
from .drafting import Drafter
from .extraction import OrderExtractor
from .evaluation import (
    format_report,
    new_run_id,
    run_cases,
    score,
    write_traces,
)
from .loading import (
    load_cases,
    load_customers,
    load_draft_set,
    load_guidelines,
    load_orders,
)
from .policy import PolicyEngine, load_policy
from .routing import LlmRouter, ReplyEvaluator, check_available
from .routing.base import Router
from .routing.llm import DEFAULT_ROUTER_MAX_TOKENS
from .routing.retrieval import DEFAULT_EMBED_MODEL, DEFAULT_K, GuidelineIndex
from .schemas import Mode

DEFAULT_GUIDELINES = Path("data/guidelines/v2/returns-escalation-policy.pdf")
DEFAULT_CASES = Path("data/cases/v0.yaml")
DEFAULT_ORDERS = Path("data/store/retail.db")
DEFAULT_CUSTOMERS = Path("data/store/retail.db")
DEFAULT_POLICY = Path("data/policy/v1/rules.yaml")
DEFAULT_MODEL = "qwen3.5:4b"
RUNS_DIR = Path("runs")


def build_router(
    mode: str,
    guidelines_path: Path,
    model: str,
    think: bool,
    top_k: int = DEFAULT_K,
    *,
    option_b_policy: PolicyEngine | None = None,
    router_max_tokens: int = DEFAULT_ROUTER_MAX_TOKENS,
) -> Router:
    if option_b_policy is not None and mode != "rag":
        raise ValueError("Option B requires RAG")
    corpus = load_guidelines(guidelines_path)

    if mode == "prompt_only":
        check_available(model)
        return LlmRouter(
            mode=Mode.PROMPT_ONLY,
            model_name=model,
            guideline_corpus_version="none",
            think=think,
            max_tokens=router_max_tokens,
        )

    if mode == "full_context":
        check_available(model)
        return LlmRouter(
            mode=Mode.FULL_CONTEXT,
            model_name=model,
            guideline_corpus_version=guidelines_path.parent.name,
            guidelines=corpus.guidelines,
            think=think,
            max_tokens=router_max_tokens,
        )

    if mode == "rag":
        check_available(model)
        check_available(DEFAULT_EMBED_MODEL)
        print(f"indexing {len(corpus.guidelines)} guidelines...")
        return LlmRouter(
            mode=Mode.RAG,
            model_name=model,
            guideline_corpus_version=guidelines_path.parent.name,
            index=GuidelineIndex(corpus.guidelines),
            top_k=top_k,
            think=think,
            evaluator=(
                ReplyEvaluator(model_name=model, policy=option_b_policy)
                if option_b_policy is not None
                else None
            ),
            max_tokens=router_max_tokens,
        )

    raise SystemExit(f"mode not implemented yet: {mode}")


def main() -> None:
    parser = argparse.ArgumentParser(prog="llmgov")
    sub = parser.add_subparsers(dest="command", required=True)

    run = sub.add_parser("run", help="route a case set and score the result")
    run.add_argument("--mode", default="rag")
    run.add_argument(
        "--architecture",
        choices=("baseline", "option-b"),
        default="baseline",
        help="use the baseline or add the searcher and evaluator to RAG",
    )
    run.add_argument(
        "--model", default=DEFAULT_MODEL, help="ollama model, LLM modes only"
    )
    run.add_argument(
        "--think",
        action="store_true",
        help="let a reasoning model think before answering (slower)",
    )
    run.add_argument(
        "--top-k", type=int, default=DEFAULT_K, help="guidelines retrieved, rag mode"
    )
    run.add_argument(
        "--router-max-tokens",
        type=int,
        default=DEFAULT_ROUTER_MAX_TOKENS,
        help="maximum tokens generated by the router",
    )
    run.add_argument("--cases", type=Path, default=DEFAULT_CASES)
    run.add_argument(
        "--case-id", action="append", help="run only this case; repeat to select more"
    )
    run.add_argument("--orders", type=Path, default=DEFAULT_ORDERS)
    run.add_argument("--customers", type=Path, default=DEFAULT_CUSTOMERS)
    run.add_argument(
        "--no-extract",
        action="store_true",
        help="take the order id from the case file instead of reading it from "
        "the customer's message",
    )
    run.add_argument(
        "--drafts",
        type=Path,
        help="reuse replies pinned from an earlier run instead of writing new ones",
    )
    run.add_argument("--policy", type=Path, default=DEFAULT_POLICY)
    run.add_argument("--guidelines", type=Path, default=DEFAULT_GUIDELINES)
    run.add_argument("--runs-dir", type=Path, default=RUNS_DIR)

    args = parser.parse_args()
    option_b = args.architecture == "option-b"
    if option_b and args.mode != "rag":
        run.error("--architecture option-b requires --mode rag")
    if args.top_k < 1 or args.router_max_tokens < 1:
        run.error("--top-k and --router-max-tokens must be positive")

    orders = load_orders(args.orders, load_customers(args.customers))
    policy = load_policy(args.policy)
    cases = load_cases(args.cases, orders, policy)
    if args.case_id:
        selected = set(args.case_id)
        missing = selected - {case.case_id for case in cases}
        if missing:
            run.error(f"unknown case IDs: {', '.join(sorted(missing))}")
        cases = [case for case in cases if case.case_id in selected]

    frozen_drafts, draft_metadata = None, None
    if args.drafts:
        frozen_drafts, draft_metadata = load_draft_set(args.drafts)
        missing = {case.case_id for case in cases} - frozen_drafts.keys()
        if option_b and missing:
            run.error(f"missing pinned drafts for: {', '.join(sorted(missing))}")
        draft_metadata["path"] = args.drafts.as_posix()

    router = build_router(
        args.mode,
        args.guidelines,
        args.model,
        args.think,
        args.top_k,
        option_b_policy=policy if option_b else None,
        router_max_tokens=args.router_max_tokens,
    )
    run_id = new_run_id(
        f"{args.mode}-option-b" if option_b else args.mode, args.runs_dir
    )

    drafter = Drafter(model_name=args.model, policy=policy)
    extractor = None if args.no_extract else OrderExtractor(model_name=args.model)
    traces = run_cases(
        cases,
        router,
        run_id,
        policy=policy,
        drafter=drafter,
        extractor=extractor,
        orders=orders,
        frozen_drafts=frozen_drafts,
        frozen_draft_metadata=draft_metadata,
    )
    metrics = score(traces)

    out = args.runs_dir / run_id
    write_traces(traces, out / "traces.jsonl")
    (out / "metrics.json").write_text(
        json.dumps(metrics.to_dict(), indent=2), encoding="utf-8"
    )

    print(format_report(metrics, f"{args.mode} (Option B)" if option_b else args.mode))
    print(f"\nwritten to {out}")


if __name__ == "__main__":
    main()
